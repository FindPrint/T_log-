def monte_carlo_estimators(
    series: Any,
    n_paths: int = 200,
    seed: int = 42,
    window: int = 80,
) -> Dict[str, Any]:
    """Uniform input-perturbation Monte Carlo across all 29 estimators."""
    x = np.asarray(series, dtype=float)
    fin = _finite(x)
    if len(fin) < max(20, window // 2):
        return {"status": "insufficient_data", "estimators": {}, "n_paths": 0, "seed": int(seed)}

    dif = np.diff(fin)
    scale = (
        float(1.4826 * np.median(np.abs(dif - np.median(dif))) / math.sqrt(2.0))
        if len(dif)
        else 0.0
    )
    if not math.isfinite(scale):
        scale = 0.0

    results: Dict[str, List[float]] = {name: [] for name, _, _ in ESTIMATORS}
    seeds: List[int] = []
    n_total_paths = max(50, int(n_paths))
    mask = np.isfinite(x)
    n_mask = int(np.sum(mask))

    for k in range(n_total_paths):
        path_seed = int(np.random.SeedSequence([int(seed), k]).generate_state(1)[0])
        seeds.append(path_seed)
        rng = np.random.default_rng(path_seed)
        perturbed = x.copy()
        if scale > 0.0:
            perturbed[mask] = perturbed[mask] + rng.normal(0.0, scale, size=n_mask)
        est = apply_estimators(perturbed)
        for name, _, _ in ESTIMATORS:
            results[name].append(est.get(name, np.nan))

    out: Dict[str, Any] = {}
    for name, vals in results.items():
        a = np.asarray(vals, dtype=float)
        f = a[np.isfinite(a)]
        out[name] = {
            "mean": float(np.mean(f)) if len(f) else float("nan"),
            "std": float(np.std(f, ddof=1)) if len(f) > 1 else float("nan"),
            "median": float(np.median(f)) if len(f) else float("nan"),
            "q05": float(np.quantile(f, 0.05)) if len(f) else float("nan"),
            "q95": float(np.quantile(f, 0.95)) if len(f) else float("nan"),
            "valid_fraction": float(len(f) / len(a)),
            "n_valid": int(len(f)),
            "n_total": int(len(a)),
        }

    return {
        "status": "ok",
        "method": "uniform input-perturbation MC; segmented cohorts",
        "n_paths": len(seeds),
        "seed": int(seed),
        "noise_scale_mad_diff": scale,
        "weighting": "equal weight per Monte Carlo path",
        "estimators": out,
        "draw_order_is_not_time": True,
    }


def _cohort_validation(
    series: Any,
    seed: int,
    n_mc_paths: int,
    window: int,
    coordinate: Any = None,
    gaussian_sigma: float = 2.0,
) -> Dict[str, Any]:
    x = np.asarray(series, dtype=float)
    n = len(x)
    coord = np.arange(n, dtype=float) if coordinate is None else np.asarray(coordinate, dtype=float)
    win = max(20, min(int(window), max(20, n // 3)))
    step = max(1, win // 6)

    mc = monte_carlo_estimators(x, n_paths=n_mc_paths, seed=seed, window=win)
    trajs, centers = _rolling_estimator_trajectories(
        x, win, step=step, coordinate=coord, return_coordinates=True
    )
    by_est: Dict[str, Any] = {}
    for i, (name, _, _) in enumerate(ESTIMATORS):
        tr = trajs[name]
        tests = _four_noise_tests(tr, seed + 1009 * i)
        deriv = _f1_f2(tr, centers, gaussian_sigma=gaussian_sigma)
        by_est[name] = {
            "n_trajectory_points": int(len(tr)),
            "tests": tests,
            "f1_f2_summary": {
                "status": deriv.get("status"),
                "f1_mean": deriv.get("f1_mean"),
                "f2_mean": deriv.get("f2_mean"),
            },
        }
    return {
        "status": "ok" if n >= win else "insufficient_data",
        "n": int(n),
        "window": int(win),
        "step": int(step),
        "per_estimator": by_est,
        "monte_carlo": mc,
    }


def estimator_validation_suite(
    series: Any,
    seed: int = 42,
    n_mc_paths: int = 200,
    control: Any = None,
    threshold_idx: Optional[int] = None,
    gaussian_sigma: float = 2.0,
) -> Dict[str, Any]:
    """Three-cohort segmented validation (initial, pre-threshold, post-threshold)."""
    x = np.asarray(series, dtype=float)
    n = len(x)
    c = np.arange(n, dtype=float) if control is None else np.asarray(control, dtype=float)
    if len(c) != n:
        raise ValueError("control must have the same length as series")

    cut = int(threshold_idx) if (threshold_idx is not None and 0 < int(threshold_idx) < n) else None
    if cut is None:
        cohorts: Dict[str, Tuple[np.ndarray, np.ndarray]] = {"initial": (x, c)}
    else:
        cohorts = {
            "initial": (x, c),
            "pre_threshold": (x[:cut], c[:cut]),
            "post_threshold": (x[cut:], c[cut:]),
        }

    win = max(20, min(128, n // 5))
    stages: Dict[str, Any] = {}
    for stage, (sx, sc) in cohorts.items():
        stages[stage] = _cohort_validation(
            sx, seed, n_mc_paths, win, coordinate=sc, gaussian_sigma=gaussian_sigma
        )
        stages[stage]["raw_target_f1_f2"] = _f1_f2(sx, sc, gaussian_sigma=gaussian_sigma)

    comparison: Dict[str, Any] = {"status": "not_applicable"}
    predictive_mc: Dict[str, Any] = {
        "status": "not_applicable",
        "interpretation": "no valid threshold or insufficient pre/post cohorts",
    }

    if cut is not None and "pre_threshold" in stages and "post_threshold" in stages:
        comparison = {"status": "ok", "per_estimator": {}}
        for name, _, _ in ESTIMATORS:
            a = stages["pre_threshold"]["monte_carlo"].get("estimators", {}).get(name, {})
            b = stages["post_threshold"]["monte_carlo"].get("estimators", {}).get(name, {})
            ma, mb = a.get("median", float("nan")), b.get("median", float("nan"))
            comparison["per_estimator"][name] = {
                "pre_mc_median": ma,
                "post_mc_median": mb,
                "delta_post_minus_pre": float(mb - ma)
                if math.isfinite(ma) and math.isfinite(mb)
                else float("nan"),
            }

        pre = stages["pre_threshold"]["monte_carlo"].get("estimators", {})
        post_obs = apply_estimators(x[cut:])
        checks: Dict[str, Any] = {}
        n_tested, n_inside = 0, 0
        for name, _, _ in ESTIMATORS:
            p = pre.get(name, {})
            obs = post_obs.get(name, float("nan"))
            lo, hi = p.get("q05", float("nan")), p.get("q95", float("nan"))
            valid = math.isfinite(obs) and math.isfinite(lo) and math.isfinite(hi)
            inside = bool(valid and lo <= obs <= hi)
            checks[name] = {
                "post_observed": obs,
                "pre_mc_q05": lo,
                "pre_mc_q95": hi,
                "inside_pre_mc_interval": inside,
                "status": "ok" if valid else "insufficient",
            }
            if valid:
                n_tested += 1
                n_inside += int(inside)
        predictive_mc = {
            "status": "ok" if n_tested else "insufficient_data",
            "method": "pre-threshold MC interval vs post-threshold observed estimate",
            "n_estimators_tested": n_tested,
            "n_inside_90pct_interval": n_inside,
            "empirical_coverage": float(n_inside / n_tested) if n_tested else float("nan"),
            "per_estimator": checks,
            "warning": "retrospective pre/post check, not an independent prospective forecast",
        }

    return {
        "status": "segmented_validation_protocol",
        "n_estimators_named": len(ESTIMATORS),
        "n_unique_callables": len(UNIQUE_ESTIMATORS),
        "threshold_idx": cut,
        "stages": stages,
        "pre_post_comparison": comparison,
        "predictive_mc_check": predictive_mc,
        "f1_f2_specification": {
            "F1": "gradient(y_smooth, p_coord)",
            "F2": "gradient(F1, p_coord)",
            "smoothing": "Gaussian",
            "gaussian_sigma": float(gaussian_sigma),
        },
    }

