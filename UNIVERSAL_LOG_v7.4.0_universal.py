def compute_tlog(
    est: Dict[str, float],
    n: int,
    series: Any = None,
    n_perm: int = 25,
    seed: int = 42,
) -> Dict[str, Any]:
    """Compute T_log complexity diagnostic calibrated against its permutation null (P8).

    When ``series`` is provided, ``d_median`` is calibrated against ``n_perm`` temporal
    permutations of ``series`` (preserving marginal distribution while breaking order):
        t_log = (d_median - d_null_median) * log(n)
        z_score = (d_median - d_null_median) / max(d_null_std, 1e-6)
    If ``series`` is omitted, falls back to uncalibrated ``d_median`` summary with
    ``t_log = NaN`` (no magic domain reference constant).
    """
    seen_fn: Set[str] = set()
    dims: List[float] = []
    for name, fn, is_dim in ESTIMATORS:
        if not is_dim:
            continue
        key = getattr(fn, "__name__", str(fn))
        if key in seen_fn:
            continue
        seen_fn.add(key)
        v = est.get(name, float("nan"))
        if math.isfinite(v):
            dims.append(float(v))

    if not dims or n <= 1:
        return {
            "t_log": float("nan"),
            "d_median": float("nan"),
            "d_null_median": float("nan"),
            "d_null_std": float("nan"),
            "z_score": float("nan"),
            "p_permutation": float("nan"),
            "n_dimension_estimators": 0,
            "calibrated": False,
            "note": "not computable — diagnostic only",
        }

    d_med = float(np.median(dims))
    if series is None or n_perm < 1:
        return {
            "t_log": float("nan"),
            "d_median": d_med,
            "d_null_median": float("nan"),
            "d_null_std": float("nan"),
            "z_score": float("nan"),
            "p_permutation": float("nan"),
            "n_dimension_estimators": len(dims),
            "calibrated": False,
            "note": "uncalibrated (pass series for permutation-null calibration) — diagnostic only",
        }

    xf = _finite(series)
    rng = np.random.default_rng(seed)
    null_medians: List[float] = []
    for _ in range(int(n_perm)):
        perm = rng.permutation(xf)
        perm_dims = [v for v in apply_dimension_estimators(perm).values() if math.isfinite(v)]
        if perm_dims:
            null_medians.append(float(np.median(perm_dims)))

    if len(null_medians) < 3:
        return {
            "t_log": float("nan"),
            "d_median": d_med,
            "d_null_median": float("nan"),
            "d_null_std": float("nan"),
            "z_score": float("nan"),
            "p_permutation": float("nan"),
            "n_dimension_estimators": len(dims),
            "calibrated": False,
            "note": "permutation null insufficient — diagnostic only",
        }

    null_arr = np.asarray(null_medians, dtype=float)
    d_null_med = float(np.median(null_arr))
    d_null_std = float(np.std(null_arr, ddof=1))
    delta = d_med - d_null_med
    t_log_cal = float(delta * math.log(n))
    z_score = float(delta / max(d_null_std, 1e-6))
    p_perm = float((1 + np.sum(np.abs(null_arr - d_null_med) >= abs(delta))) / (len(null_arr) + 1))

    return {
        "t_log": t_log_cal,
        "d_median": d_med,
        "d_null_median": d_null_med,
        "d_null_std": d_null_std,
        "z_score": z_score,
        "p_permutation": p_perm,
        "n_dimension_estimators": len(dims),
        "calibrated": True,
        "note": "permutation-calibrated diagnostic only, never proof",
    }

