"""Locked pattern-level prediction across validated analyses."""


import math
from collections import Counter
from typing import Any, Dict, List, Set, Tuple


def _motif_of_analysis(res: Dict[str, Any]) -> Set[Tuple[str, str]]:
    """Extract complementary estimator pairs from the target flux only."""
    target_name = None
    try:
        target_name = res.get("universal_contract", {}).get("target")
    except Exception:
        pass

    pairs: Set[Tuple[str, str]] = set()
    try:
        inter = res.get("levels", {}).get("L7_interactions", {})
        per = inter.get("per_flux", {})
        if target_name and target_name in per:
            per = {target_name: per[target_name]}
        for pf in per.values():
            for pr in pf.get("complementary_pairs", []):
                if pr.get("estimator_a") and pr.get("estimator_b"):
                    pairs.add((str(pr["estimator_a"]), str(pr["estimator_b"])))
                elif pr.get("estimator_pre") and pr.get("estimator_post"):
                    pairs.add((str(pr["estimator_pre"]), str(pr["estimator_post"])))
    except Exception:
        pass
    return pairs


def _holdout_motif_check(res: Dict[str, Any]) -> Tuple[bool, str]:
    """Temporal holdout check: build motif from earlier segments and verify on final segment."""
    try:
        inter = res.get("levels", {}).get("L7_interactions", {})
        segs = inter.get("segments", [])
        if len(segs) < 3:
            return False, "fewer than 3 segments"
        last = len(segs) - 1
        per_flux = inter.get("per_flux", {})
        tgt = res.get("universal_contract", {}).get("target")
        if tgt and tgt in per_flux:
            per_flux = {tgt: per_flux[tgt]}
        if not per_flux:
            return False, "missing per_flux interactions"

        oks, tot = 0, 0
        for pf in per_flux.values():
            profiles = pf.get("profiles", {})
            train_candidates: List[Tuple[str, float]] = []
            for name, profile in profiles.items():
                vals = profile.get("informativeness_per_segment", [])
                train_vals = [
                    v for v in vals[:last] if isinstance(v, (int, float)) and math.isfinite(v)
                ]
                if train_vals:
                    train_candidates.append((name, float(max(train_vals))))
            if not train_candidates:
                continue
            train_candidates.sort(key=lambda z: z[1], reverse=True)
            predicted = {name for name, _ in train_candidates[:3]}
            last_top = pf.get("per_segment_top", {}).get(f"segment_{last}", [])
            last_names = {x.get("estimator") for x in last_top}
            tot += 1
            if predicted & last_names:
                oks += 1
        if tot == 0:
            return False, "no computable motif on training segments"
        return (oks / tot >= 0.5), f"{oks}/{tot} flux(es): training top overlaps held-out segment"
    except Exception as exc:
        return False, f"holdout error: {exc}"


def predict_universal(analyses: List[Dict[str, Any]], question: str) -> Dict[str, Any]:
    """Locked cross-study motif prediction; refuses unless every quality gate passes."""
    reasons: List[str] = []
    if not isinstance(question, str) or not question.strip():
        reasons.append(
            "refined research question missing: state the hypothesis and falsification criterion"
        )
    if not isinstance(analyses, list) or len(analyses) < 5:
        n_got = len(analyses) if isinstance(analyses, list) else 0
        reasons.append(f"insufficient analyses: {n_got}/5 minimum required on the same protocol")
    if reasons:
        return {
            "status": "refused",
            "prediction": None,
            "reasons": reasons,
            "note": "prediction refused — gather >= 5 comparable validated analyses first",
        }

    metas = []
    for i, res in enumerate(analyses):
        md = res.get("prediction_metadata", {}) if isinstance(res, dict) else {}
        qid, pid = md.get("question_id"), md.get("protocol_id")
        if not qid or not pid:
            reasons.append(f"analysis {i}: missing question_id/protocol_id (protocol identity required)")
        else:
            metas.append((str(qid), str(pid)))
    if metas and (len(metas) != len(analyses) or len(set(metas)) != 1):
        reasons.append("incompatible analyses: question_id or protocol_id mismatch")

    for i, res in enumerate(analyses):
        g = res.get("grade", {}).get("grade") if isinstance(res, dict) else None
        if g not in ("A", "B"):
            reasons.append(f"analysis {i}: grade is {g} (requires A or B)")

        cfg_res = res.get("config", {}) if isinstance(res, dict) else {}
        l7_res = res.get("levels", {}).get("L7_interactions", {}) if isinstance(res, dict) else {}
        if cfg_res.get("run_complexity_diagnostics") is not True or l7_res.get("status") != "ok":
            reasons.append(
                f"analysis {i}: exploratory L7 complexity diagnostics not active/available "
                "(requires run_complexity_diagnostics=True)"
            )

        scan = res.get("scan", {}) if isinstance(res, dict) else {}
        p_corr = scan.get(
            "p_channel_adjusted",
            scan.get("p_scan_null", scan.get("p_permutation_scan_corrected", scan.get("p_permutation"))),
        )
        if not (isinstance(p_corr, (int, float)) and math.isfinite(p_corr) and p_corr <= 0.05):
            reasons.append(f"analysis {i}: adjusted scan p={p_corr} (requires <= 0.05)")

        wf_dict = res.get("walk_forward", {}) if isinstance(res, dict) else {}
        wf = wf_dict.get("mean_f1")
        wf_votes = wf_dict.get("n_splits_used", 0)
        if not (isinstance(wf, (int, float)) and wf >= 0.50 and wf_votes >= 2):
            reasons.append(f"analysis {i}: walk-forward F1={wf}, votes={wf_votes} (requires >= 0.50 and >= 2)")

        stab = (
            res.get("falsification", {}).get("multi_window", {}).get("stability")
            if isinstance(res, dict)
            else None
        )
        if not (isinstance(stab, (int, float)) and stab >= 0.60):
            reasons.append(f"analysis {i}: multi-window stability={stab} (requires >= 0.60)")

    motifs = [_motif_of_analysis(r) for r in analyses]
    cnt: Counter[Tuple[str, str]] = Counter()
    for m in motifs:
        for pair in m:
            cnt[pair] += 1
    common = [pair for pair, c in cnt.items() if c >= 3]
    if not common:
        reasons.append("no shared motif: no complementary pair appears in >= 3 analyses")

    hold_ok: List[bool] = []
    hold_details: List[str] = []
    for i, res in enumerate(analyses):
        ok, det = _holdout_motif_check(res)
        hold_ok.append(ok)
        hold_details.append(f"analysis {i}: {det}")
    if sum(hold_ok) / max(len(hold_ok), 1) < 0.5:
        reasons.append(
            f"held-out segment check failed: {sum(hold_ok)}/{len(hold_ok)} pass (requires >= 50%)"
        )

    if reasons:
        return {
            "status": "refused",
            "prediction": None,
            "reasons": reasons,
            "holdout_details": hold_details,
            "note": "prediction refused — motif is not yet stable across replications",
        }

    common_sorted = sorted(common, key=lambda pr: cnt[pr], reverse=True)[:3]
    motif = [
        {"estimator_a": a, "estimator_b": b, "n_analyses_sharing": int(cnt[(a, b)])}
        for a, b in common_sorted
    ]
    return {
        "status": "allowed",
        "question": question,
        "motif": motif,
        "prediction": {
            "type": "next_segment_profile",
            "statement": (
                "IF the regime holds, THEN the next segment should show late estimator (b) "
                "informative (|Cohen-d| >= 0.8) and early estimator (a) non-informative (< 0.5)."
            ),
            "pairs": motif,
            "interval": "late informativeness |Cohen-d| >= 0.8, early < 0.5 (never point prediction)",
            "condition": "same protocol, same question, grade A/B on incoming segment",
        },
        "falsifiable_test": (
            "Analyze the next segment with analyze(): if late estimator (b) is NOT among top "
            "informative estimators, the motif prediction is falsified and rejected."
        ),
        "holdout_details": hold_details,
        "note": "Interval motif prediction only; must be verified on unseen future segment.",
    }

