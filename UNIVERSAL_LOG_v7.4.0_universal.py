def load_universal_dataset(
    df: pd.DataFrame,
    control: Optional[Any] = None,
    target: Optional[Any] = None,
    fluxes: Optional[Sequence[Any]] = None,
    source_name: str = "dataframe",
    source_hash: str = "",
) -> UniversalDataset:
    """Infer control, target, and auxiliary fluxes with zero domain priors.

    - Control: explicitly provided, else first strictly monotonic numeric column,
      else synthetic row index ``__index__`` (if >= 2 numeric columns exist or
      if target is explicitly provided with >= 1 numeric column).
    - Target: explicitly provided, else first numeric column != control.
    - Fluxes: all numeric columns != control (normalized-name match excluded).
    - Rows with NaN/Inf in control or target are dropped explicitly and logged,
      never silently imputed.
    """
    if df is None or len(df) == 0:
        raise ValueError("Input DataFrame is empty.")

    numeric = df.select_dtypes(include=[np.number]).columns.tolist()
    if control is None and target is None and len(numeric) < 2:
        raise ValueError(f"At least 2 numeric columns are required, found {numeric}.")
    if len(numeric) < 1:
        raise ValueError("At least 1 numeric column is required.")

    if control is not None and control not in df.columns:
        raise ValueError(f"Control column '{control}' not found. Available: {list(df.columns)}")

    control_name = control
    if control_name is None:
        mono = [
            c
            for c in numeric
            if len(_finite(df[c].values)) >= 2
            and bool(np.all(np.diff(_finite(df[c].values)) > 0))
        ]
        control_name = mono[0] if mono else None

    if control_name is None:
        control_name = "__index__"
        control_values = np.arange(len(df), dtype=float)
    else:
        control_values = pd.to_numeric(df[control_name], errors="coerce").to_numpy(dtype=float)

    if target is not None and target not in df.columns:
        raise ValueError(f"Target column '{target}' not found. Available: {list(df.columns)}")

    if target is not None:
        target_name = target
    else:
        target_name = next((c for c in numeric if c != control_name), numeric[0])

    if target_name in df.columns:
        target_values = pd.to_numeric(df[target_name], errors="coerce").to_numpy(dtype=float)
    else:
        target_values = control_values.copy()

    def _norm(s: Any) -> str:
        return "".join(ch for ch in str(s).lower() if ch.isalnum())

    ctrl_norm = _norm(control_name)
    if fluxes is None:
        flux_names = [c for c in numeric if _norm(c) != ctrl_norm]
    else:
        flux_names = [c for c in fluxes if c in df.columns and _norm(c) != ctrl_norm]

    order = np.argsort(control_values, kind="stable")
    c_sorted = control_values[order]
    y_sorted = target_values[order]
    mask = np.isfinite(c_sorted) & np.isfinite(y_sorted)
    n_drop = int((~mask).sum())
    if n_drop:
        print(
            f"[DATA] Dropped {n_drop}/{len(df)} rows with non-finite control/target. "
            "No silent imputation performed.",
            flush=True,
        )

    c_sorted = c_sorted[mask]
    y_sorted = y_sorted[mask]
    control_monotone = bool(len(c_sorted) >= 2 and np.all(np.diff(c_sorted) > 0))

    fluxes_dict: Dict[str, np.ndarray] = {}
    for name in flux_names:
        arr = pd.to_numeric(df[name], errors="coerce").to_numpy(dtype=float)
        fluxes_dict[str(name)] = arr[order][mask]

    if str(target_name) not in fluxes_dict and target_name in df.columns:
        fluxes_dict[str(target_name)] = y_sorted

    return UniversalDataset(
        control=c_sorted,
        control_name=str(control_name),
        target=y_sorted,
        target_name=str(target_name),
        fluxes=fluxes_dict,
        flux_names=list(fluxes_dict.keys()),
        n=int(len(c_sorted)),
        control_monotone=control_monotone,
        source_hash=source_hash,
        source_name=source_name,
        dropped_rows=n_drop,
    )


def demo_dataset(kind: str = "logistic", n: int = 300, seed: int = 42) -> pd.DataFrame:
    """Generate a domain-agnostic synthetic dataset ('step', 'logistic', or 'null')."""
    rng = np.random.default_rng(seed)
    x = np.linspace(0.0, 100.0, n)
    if kind == "step":
        y = np.where(x < 50.0, 0.0, 1.0) + rng.normal(0.0, 0.15, n)
    elif kind == "null":
        y = rng.normal(0.0, 1.0, n)
    else:  # logistic
        y = 1.0 / (1.0 + np.exp(-(x - 50.0) / 5.0)) + rng.normal(0.0, 0.08, n)

    return pd.DataFrame(
        {
            "axis": x,
            "observable": y,
            "observable_noisy": y + rng.normal(0.0, 0.1, n),
            "pure_noise": rng.normal(0.0, 1.0, n),
        }
    )


