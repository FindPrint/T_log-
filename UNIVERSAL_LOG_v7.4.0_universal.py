def _null_bars_svg(observed_d: float, falsif: Dict[str, Any]) -> str:
    wn = falsif.get("white_noise_null", {}) if isinstance(falsif, dict) else {}
    sh = falsif.get("shuffled_target_null", {}) if isinstance(falsif, dict) else {}
    pc = falsif.get("permuted_control_same_cut", {}) if isinstance(falsif, dict) else {}
    ar1 = falsif.get("ar1_surrogate_null", {}) if isinstance(falsif, dict) else {}

    items = [
        ("Observed |d|", abs(observed_d) if _is_finite(observed_d) else 0.0, "#1d4ed8"),
        ("AR(1) Null p95 |d|", float(ar1.get("ar1_null_p95_abs_d")) if _is_finite(ar1.get("ar1_null_p95_abs_d")) else 0.0, "#64748b"),
        ("White-Noise Null |d|", abs(float(wn.get("cohen_d"))) if _is_finite(wn.get("cohen_d")) else 0.0, "#64748b"),
        ("Shuffled Null |d|", abs(float(sh.get("cohen_d"))) if _is_finite(sh.get("cohen_d")) else 0.0, "#64748b"),
        ("Permuted Cut Med |d|", abs(float(pc.get("d_permuted_median"))) if _is_finite(pc.get("d_permuted_median")) else 0.0, "#94a3b8"),
    ]
    vmax = max([v for _, v, _ in items] + [0.5]) * 1.12
    w, h = 440.0, 195.0
    pad_l, pad_r, pad_t = 152.0, 56.0, 14.0
    bw = w - pad_l - pad_r
    rows_svg: List[str] = []
    for idx, (label, val, color) in enumerate(items):
        y = pad_t + idx * 34.0
        bar_w = max(2.0, (val / vmax) * bw) if vmax > 0 else 2.0
        rows_svg.append(
            f"<text x='{(pad_l - 8):.1f}' y='{(y + 16):.1f}' text-anchor='end' class='svg-tick'>{_esc(label)}</text>"
            f"<rect x='{pad_l:.1f}' y='{y + 3:.1f}' width='{bw:.1f}' height='18' rx='4' fill='#f1f5f9'/>"
            f"<rect x='{pad_l:.1f}' y='{y + 3:.1f}' width='{bar_w:.1f}' height='18' rx='4' fill='{color}'/>"
            f"<text x='{(pad_l + bar_w + 6):.1f}' y='{(y + 16):.1f}' class='svg-tick-bold'>{val:.3f}</text>"
        )
    if _is_finite(observed_d) and abs(observed_d) > 0:
        half_x = pad_l + (0.5 * abs(observed_d) / vmax) * bw
        rows_svg.append(
            f"<line x1='{half_x:.1f}' y1='{pad_t:.1f}' x2='{half_x:.1f}' y2='{(h - 14):.1f}' "
            f"stroke='#dc2626' stroke-width='1.3' stroke-dasharray='4,3'/>"
            f"<text x='{half_x:.1f}' y='{(h - 2):.1f}' text-anchor='middle' fill='#dc2626' font-size='10'>0.5 * |d_obs|</text>"
        )
    return f"<svg viewBox='0 0 {int(w)} {int(h)}' class='bar-svg'>{''.join(rows_svg)}</svg>"


def _multi_window_svg(falsif: Dict[str, Any], ctrl: np.ndarray) -> str:
    mw = falsif.get("multi_window", {}) if isinstance(falsif, dict) else {}
    vals = [float(v) for v in mw.get("threshold_values", []) if _is_finite(v)]
    if len(vals) == 0 or len(ctrl) == 0:
        return "<div class='empty-box'>No multi-window thresholds recorded.</div>"
    xmin, xmax = float(np.nanmin(ctrl)), float(np.nanmax(ctrl))
    if xmax <= xmin:
        xmax = xmin + 1.0
    w, h = 440.0, 120.0
    pad_l, pad_r = 28.0, 28.0
    pw = w - pad_l - pad_r
    dots: List[str] = []
    for i, v in enumerate(vals):
        x = pad_l + max(0.0, min(1.0, (v - xmin) / (xmax - xmin))) * pw
        y = 34.0 + i * 18.0
        dots.append(
            f"<circle cx='{x:.1f}' cy='{y:.1f}' r='5.5' fill='#0284c7'/>"
            f"<text x='{(x + 9):.1f}' y='{(y + 4):.1f}' class='svg-tick'>w#{i+1}: {_fmt(v, '.4g')}</text>"
        )
    return (
        f"<svg viewBox='0 0 {int(w)} {int(h)}' class='bar-svg'>"
        f"<line x1='{pad_l:.1f}' y1='96' x2='{(w - pad_r):.1f}' y2='96' stroke='#94a3b8' stroke-width='2'/>"
        f"<text x='{pad_l:.1f}' y='112' class='svg-tick'>{_fmt(xmin, '.4g')}</text>"
        f"<text x='{(w - pad_r):.1f}' y='112' text-anchor='end' class='svg-tick'>{_fmt(xmax, '.4g')}</text>"
        f"{''.join(dots)}</svg>"
    )


