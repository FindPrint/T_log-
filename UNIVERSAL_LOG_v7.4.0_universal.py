def _step4_fft_spectral(y: Any) -> Dict[str, Any]:
    yf = _finite(y)
    if len(yf) < 16 or np.std(yf) == 0.0:
        return {
            "status": "insufficient_or_constant",
            "spectral_entropy": float("nan"),
            "dominant_fraction": float("nan"),
        }
    p = np.abs(np.fft.rfft(yf - np.mean(yf))) ** 2
    if len(p) > 0:
        p[0] = 0.0
    p = p[p > 0.0]
    if len(p) < 2:
        return {
            "status": "insufficient",
            "spectral_entropy": float("nan"),
            "dominant_fraction": float("nan"),
        }
    q = p / np.sum(p)
    ent = float(-np.sum(q * np.log(q)) / math.log(len(q)))
    dom = float(np.max(q))
    return {
        "status": "ok",
        "spectral_entropy": ent,
        "dominant_fraction": dom,
        "definition": "FFT spectral entropy + dominant power fraction",
    }


