def apply_estimators(series: Any) -> Dict[str, float]:
    """Evaluate all 29 estimators on a series, sharing expensive graph intermediates."""
    xf = _finite(series)
    adj_cache: Optional[List[Set[int]]] = None
    adj_computed = False
    out: Dict[str, float] = {}

    for name, fn, _ in ESTIMATORS:
        try:
            if name in ("VisibilityGraph", "GraphCluster"):
                if not adj_computed:
                    adj_cache = _natural_visibility_adjacency(xf)
                    adj_computed = True
                if name == "VisibilityGraph":
                    out[name] = _safe_float(_visibility_tail_from_adj(adj_cache))
                else:
                    out[name] = _safe_float(_graph_cluster_from_adj(adj_cache))
            else:
                out[name] = _safe_float(fn(xf))
        except Exception:
            out[name] = float("nan")
    return out


