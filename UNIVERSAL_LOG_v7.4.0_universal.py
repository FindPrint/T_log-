def _rolling_estimator_trajectories(
    series: Any,
    window: int,
    step: int = 5,
    coordinate: Any = None,
    return_coordinates: bool = False,
) -> Any:
    """Compute sliding-window estimator trajectories without NaN imputation."""
    x = np.asarray(series, dtype=float)
    c = np.arange(len(x), dtype=float) if coordinate is None else np.asarray(coordinate, dtype=float)
    if len(c) != len(x):
        raise ValueError("coordinate must have the same length as series")
    if window < 8 or len(x) < window:
        empty = {name: np.array([], dtype=float) for name, _, _ in ESTIMATORS}
        return (empty, np.array([], dtype=float)) if return_coordinates else empty

    rows: List[Dict[str, float]] = []
    centers: List[float] = []
    for i in range(0, len(x) - window + 1, max(1, step)):
        rows.append(apply_estimators(x[i : i + window]))
        cc = c[i : i + window]
        centers.append(float(np.nanmean(cc)) if np.isfinite(cc).any() else float("nan"))

    trajectories = {
        name: np.asarray([r.get(name, np.nan) for r in rows], dtype=float)
        for name, _, _ in ESTIMATORS
    }
    centers_arr = np.asarray(centers, dtype=float)
    return (trajectories, centers_arr) if return_coordinates else trajectories


def _step1_white_noise_q5(y: Any, seed: int = 42, n_perm: int = 199) -> Dict[str, Any]:
    yf = _finite(y)
    if len(yf) < 8 or np.std(yf) == 0.0:
        return {"status": "insufficient_or_constant", "statistic": float("nan"), "p_value": float("nan")}
    obs = float(np.corrcoef(yf[:-1], yf[1:])[0, 1])
    rng = np.random.default_rng(seed)
    null = []
    for _ in range(n_perm):
        z = rng.permutation(yf)
        null.append(float(np.corrcoef(z[:-1], z[1:])[0, 1]))
    lo, hi = np.quantile(null, [0.025, 0.975])
    return {
        "status": "ok",
        "statistic": obs,
        "null_q025": float(lo),
        "null_q975": float(hi),
        "p_value": float((1 + sum(abs(v) >= abs(obs) for v in null)) / (n_perm + 1)),
        "flag": bool(obs < lo or obs > hi),
        "definition": "provisional Q5: lag-1 autocorrelation against permutation null",
    }


def _step2_local_volatility(y: Any) -> Dict[str, Any]:
    yf = _finite(y)
    if len(yf) < 8 or np.std(yf, ddof=1) == 0.0:
        return {"status": "insufficient_or_constant", "ratio": float("nan"), "flag": None}
    w = max(3, len(yf) // 4)
    local = [np.std(yf[i : i + w], ddof=1) for i in range(0, len(yf) - w + 1, max(1, w // 2))]
    ratio = float(np.max(local) / np.std(yf, ddof=1)) if local else float("nan")
    return {
        "status": "ok",
        "ratio": ratio,
        "flag": bool(ratio > 1.5),
        "definition": "max local std / global std; provisional threshold 1.5",
    }


