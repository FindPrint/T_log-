def scan_multivariate_channels(
    control: Any,
    fluxes: Dict[str, np.ndarray],
    window: int = 40,
    min_group: int = 4,
    n_perm: int = 200,
    seed: int = 42,
) -> Dict[str, Any]:
    """Composite multivariate break scan across all fluxes via P2 stability weighting.

    Preserves instantaneous cross-flux correlations by permuting the time index
    jointly across all fluxes when computing the scan-corrected p-value.
    """
    x = np.asarray(control, dtype=float)
    n = len(x)
    usable: List[Tuple[str, np.ndarray]] = []
    for name, arr in fluxes.items():
        a = np.asarray(arr, dtype=float)
        if len(a) == n and np.all(np.isfinite(a)) and np.std(a) > 0.0:
            usable.append((name, a))

    if len(usable) < 2:
        return {
            "status": "univariate_only",
            "n_fluxes_usable": len(usable),
            "note": "at least 2 finite non-constant fluxes required for multivariate composite scan",
        }

    if n < 2 * min_group + 4:
        return {"status": "insufficient_data", "n_fluxes_usable": len(usable)}

    w = int(max(min_group, min(window, max(min_group, n // 3))))
    d_curves: List[np.ndarray] = []
    weights: List[float] = []
    idx_ref: Optional[np.ndarray] = None

    for _, arr in usable:
        idx_c, d_c = _sliding_cohen_d_vec(arr, w)
        if len(d_c) == 0:
            continue
        idx_ref = idx_c
        d_clean = np.where(np.isfinite(d_c), d_c, 0.0)
        d_curves.append(d_clean)
        weights.append(stability_weight(np.abs(d_clean)))

    if idx_ref is None or len(d_curves) < 2:
        return {"status": "insufficient_data", "n_fluxes_usable": len(usable)}

    w_arr = np.asarray(weights, dtype=float)
    w_sum = float(np.sum(w_arr))
    w_norm = w_arr / w_sum if w_sum > 0.0 else np.full(len(w_arr), 1.0 / len(w_arr))

    d_mat = np.vstack(d_curves)  # (K, n_cands)
    comp = np.sqrt(np.sum((w_norm[:, None]) * (d_mat ** 2), axis=0))
    pos = int(np.argmax(comp))
    best_idx = int(idx_ref[pos])
    obs_comp = float(comp[pos])

    per_flux_at_t0 = {
        name: float(d_mat[k, pos]) for k, (name, _) in enumerate(usable)
    }

    rng = np.random.default_rng(seed + 404)
    null_max: List[float] = []
    for _ in range(int(n_perm)):
        perm = rng.permutation(n)
        d_perm_list = []
        for _, arr in usable:
            _, dp = _sliding_cohen_d_vec(arr[perm], w)
            d_perm_list.append(np.where(np.isfinite(dp), dp, 0.0))
        d_pmat = np.vstack(d_perm_list)
        comp_p = np.sqrt(np.sum((w_norm[:, None]) * (d_pmat ** 2), axis=0))
        null_max.append(float(np.max(comp_p)))

    null_arr = np.asarray(null_max, dtype=float)
    p_corr = (
        (1.0 + float(np.sum(null_arr >= obs_comp))) / (len(null_arr) + 1.0)
        if len(null_arr)
        else float("nan")
    )

    return {
        "status": "ok",
        "idx": best_idx,
        "control_value": float(x[best_idx]),
        "composite_effect": obs_comp,
        "p_permutation_scan_corrected": float(p_corr),
        "window_used": w,
        "n_fluxes": len(usable),
        "flux_weights": {usable[k][0]: float(w_norm[k]) for k in range(len(usable))},
        "per_flux_cohen_d_at_threshold": per_flux_at_t0,
    }


def detect_multiple_thresholds(
    control: Any,
    target: Any,
    min_group: int = 4,
    min_seg_len: int = 40,
    min_cohen_d: float = 0.5,
    max_p_perm: float = 0.05,
    max_thresholds: int = 5,
    n_perm: int = 100,
    seed: int = 42,
) -> Dict[str, Any]:
    """Iterative binary segmentation finding multiple significant mean-shift thresholds."""
    x = np.asarray(control, dtype=float)
    y = np.asarray(target, dtype=float)
    n = len(y)
    if n < min_seg_len:
        return {"status": "insufficient_data", "n_thresholds": 0, "thresholds": []}

    found: List[Dict[str, Any]] = []
    queue: List[Tuple[int, int]] = [(0, n)]
    step_seed = seed + 606

    while queue and len(found) < int(max_thresholds):
        # Process longest candidate segment first
        queue.sort(key=lambda seg: seg[1] - seg[0], reverse=True)
        lo, hi = queue.pop(0)
        seg_len = hi - lo
        if seg_len < min_seg_len:
            continue
        w = int(max(min_group, min(seg_len // 5, seg_len // 3)))
        if seg_len < 2 * w + 2:
            continue

        x_seg, y_seg = x[lo:hi], y[lo:hi]
        d_seg, local_idx = _scan_max_d(x_seg, y_seg, window=w, min_group=min_group)
        if local_idx is None or not math.isfinite(d_seg) or abs(d_seg) < min_cohen_d:
            continue

        p_seg, _, _ = scan_corrected_p(
            x_seg,
            y_seg,
            window=w,
            min_group=min_group,
            n_perm=n_perm,
            seed=step_seed,
        )
        step_seed += 1
        if not math.isfinite(p_seg) or p_seg > max_p_perm:
            continue

        global_idx = int(lo + local_idx)
        found.append(
            {
                "idx": global_idx,
                "control_value": float(x[global_idx]),
                "cohen_d": float(d_seg),
                "p_permutation_scan_corrected": float(p_seg),
                "window_used": w,
                "segment_start_idx": int(lo),
                "segment_end_idx": int(hi),
            }
        )
        if global_idx - lo >= min_seg_len:
            queue.append((lo, global_idx))
        if hi - global_idx >= min_seg_len:
            queue.append((global_idx, hi))

    found.sort(key=lambda item: item["control_value"])
    return {
        "status": "ok",
        "n_thresholds": len(found),
        "thresholds": found,
    }

