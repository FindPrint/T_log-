def cohen_d(a: Any, b: Any) -> float:
    """Compute standardized effect size (mean(b) - mean(a)) / pooled_std.

    Positive values indicate group ``b`` has a higher mean than group ``a``.
    Returns NaN if either group has fewer than 2 finite observations or if pooled
    standard deviation is non-finite. Returns 0.0 when both groups are constant
    with identical means.
    """
    a_fin = _finite(a)
    b_fin = _finite(b)
    if len(a_fin) < 2 or len(b_fin) < 2:
        return float("nan")

    ma = float(np.mean(a_fin))
    mb = float(np.mean(b_fin))
    va = float(np.var(a_fin, ddof=1))
    vb = float(np.var(b_fin, ddof=1))
    denom = max(len(a_fin) + len(b_fin) - 2, 1)
    pooled = math.sqrt(((len(a_fin) - 1) * va + (len(b_fin) - 1) * vb) / denom)
    if pooled == 0.0 or not math.isfinite(pooled):
        return 0.0 if ma == mb else float("nan")
    return (mb - ma) / pooled


def bootstrap_ci_cohen_d(
    a: Any,
    b: Any,
    n_boot: int = 200,
    seed: int = 42,
    alpha: float = 0.05,
) -> Tuple[float, float, float]:
    """Compute Cohen's d and its percentile bootstrap confidence interval."""
    d = cohen_d(a, b)
    if not math.isfinite(d):
        return d, float("nan"), float("nan")

    a_fin = _finite(a)
    b_fin = _finite(b)
    rng = np.random.default_rng(seed)
    na, nb = len(a_fin), len(b_fin)
    n_b = int(n_boot)

    # Vectorized bootstrap resampling
    idx_a = rng.integers(0, na, size=(n_b, na))
    idx_b = rng.integers(0, nb, size=(n_b, nb))
    samp_a = a_fin[idx_a]
    samp_b = b_fin[idx_b]

    ma = np.mean(samp_a, axis=1)
    mb = np.mean(samp_b, axis=1)
    va = np.var(samp_a, axis=1, ddof=1)
    vb = np.var(samp_b, axis=1, ddof=1)
    pooled = np.sqrt(((na - 1) * va + (nb - 1) * vb) / max(na + nb - 2, 1))

    with np.errstate(divide="ignore", invalid="ignore"):
        boots = np.where(pooled > 0.0, (mb - ma) / pooled, np.where(ma == mb, 0.0, np.nan))

    boots = boots[np.isfinite(boots)]
    if len(boots) < 10:
        return float(d), float("nan"), float("nan")

    lo, hi = np.percentile(boots, [100.0 * alpha / 2.0, 100.0 * (1.0 - alpha / 2.0)])
    return float(d), float(lo), float(hi)


def permutation_p_value(a: Any, b: Any, n_perm: int = 500, seed: int = 42) -> float:
    """Compute exact two-sided Monte Carlo permutation p-value for Cohen's d."""
    d_obs = cohen_d(a, b)
    if not math.isfinite(d_obs):
        return float("nan")

    a_fin = _finite(a)
    b_fin = _finite(b)
    pooled = np.concatenate([a_fin, b_fin])
    na = len(a_fin)
    nb = len(b_fin)
    n_tot = na + nb
    rng = np.random.default_rng(seed)
    n_p = int(n_perm)
    denom_df = max(n_tot - 2, 1)

    # Vectorized permutations via random keys + argpartition/argsort
    # Using exact pooled statistics invariant to permutation to compute Cohen's d fast:
    # Since sum_a + sum_b = S and sum2_a + sum2_b = S2, we only need sample_a!
    total_sum = float(np.sum(pooled))
    total_sum2 = float(np.sum(pooled * pooled))
    abs_obs = abs(d_obs)

    count = 0
    for _ in range(n_p):
        perm = rng.permutation(pooled)
        pa = perm[:na]
        sa = float(np.sum(pa))
        s2a = float(np.sum(pa * pa))
        sb = total_sum - sa
        s2b = total_sum2 - s2a
        ma = sa / na
        mb = sb / nb
        va = max(0.0, (s2a - sa * ma) / max(na - 1, 1))
        vb = max(0.0, (s2b - sb * mb) / max(nb - 1, 1))
        sp = math.sqrt(((na - 1) * va + (nb - 1) * vb) / denom_df)
        if sp > 0.0 and math.isfinite(sp):
            dp = (mb - ma) / sp
            if abs(dp) >= abs_obs:
                count += 1
        elif ma == mb and 0.0 >= abs_obs:
            count += 1

    return float((count + 1) / (n_p + 1))


def stability_weight(values: Any) -> float:
    """Inverse-CV stability weight: 1 / (1 + CV).

    Returns 0.0 for empty inputs and 1.0 when fewer than 2 finite values exist
    (callers needing genuine multi-point stability should check sample count).
    """
    v = _finite(values)
    if len(v) == 0:
        return 0.0
    if len(v) < 2:
        return 1.0
    sd = float(np.std(v))
    m = abs(float(np.mean(v)))
    if m == 0.0:
        return 0.5
    return float(1.0 / (1.0 + sd / m))

