def compute_interactions(
    ds: UniversalDataset,
    cascade: Dict[str, Any],
    cfg: UniversalConfig,
) -> Dict[str, Any]:
    """Compute L7 convergence and divergence across a fixed grid centered on T0."""
    n = ds.n
    t0_idx: Optional[int] = None
    if isinstance(cascade, dict):
        v0 = cascade.get("T0", {})
        if isinstance(v0, dict) and v0.get("idx") is not None and math.isfinite(v0.get("idx", float("nan"))):
            t0_idx = int(v0["idx"])

    if t0_idx is None:
        return {
            "status": "insufficient_data",
            "segments": [],
            "per_flux": {},
            "summary": {
                "n_segments": 0,
                "n_fluxes": 0,
                "total_complementary_pairs": 0,
                "definition": "no T0 available; L7 grid unavailable",
            },
        }

    w = max(20, n // 10)
    bidx = sorted({b for b in [t0_idx - 2 * w, t0_idx - w, t0_idx + w, t0_idx + 2 * w] if 0 < b < n})
    min_sep = max(10, n // 20)
    kept: List[int] = []
    for b in bidx:
        if not kept or (b - kept[-1] >= min_sep and n - b >= min_sep):
            kept.append(b)
    bounds = [0] + kept + [n]

    segments: List[Dict[str, Any]] = []
    for s in range(len(bounds) - 1):
        a, b = bounds[s], bounds[s + 1]
        if b <= a:
            continue
        if b <= t0_idx:
            pos = "pre_T0"
        elif a >= t0_idx:
            pos = "post_T0"
        else:
            pos = "at_T0"
        segments.append(
            {
                "segment": s,
                "start_idx": int(a),
                "end_idx": int(b),
                "length": int(b - a),
                "control_start": float(ds.control[a]),
                "control_end": float(ds.control[b - 1]),
                "position": pos,
            }
        )

    per_flux: Dict[str, Any] = {}
    total_pairs = 0
    for fname in ds.flux_names:
        win_vals: List[List[Dict[str, float]]] = []
        series = ds.fluxes[fname]
        win_len = min(128, max(40, len(series) // 12))
        est_per_seg: List[Dict[str, float]] = []

        for seg in segments:
            seg_series = series[seg["start_idx"] : seg["end_idx"]]
            if len(seg_series) < win_len:
                est_per_seg.append({name: float("nan") for name, _, _ in UNIQUE_ESTIMATORS})
                win_vals.append([])
                continue
            windows = [seg_series[i : i + win_len] for i in range(0, len(seg_series) - win_len + 1, 5)]
            per_win = [apply_estimators(win) for win in windows]
            med: Dict[str, float] = {}
            for name, _, _ in UNIQUE_ESTIMATORS:
                vals = [d.get(name, float("nan")) for d in per_win]
                vals = [v for v in vals if math.isfinite(v)]
                med[name] = float(np.median(vals)) if vals else float("nan")
            est_per_seg.append(med)
            win_vals.append(per_win)

        profiles: Dict[str, Any] = {}
        for name, _, _ in UNIQUE_ESTIMATORS:
            vals = [est_per_seg[s].get(name, float("nan")) for s in range(len(segments))]
            finite = [v for v in vals if math.isfinite(v)]
            if len(finite) < 2:
                profiles[name] = {
                    "values_per_segment": vals,
                    "median_across_segments": float("nan"),
                    "informativeness_per_segment": [float("nan")] * len(segments),
                    "peak_segment": None,
                    "peak_informativeness": float("nan"),
                    "delta_post_minus_pre": float("nan"),
                    "sign_post_minus_pre": "unknown",
                }
                continue

            med_val = float(np.median(finite))
            infos: List[float] = []
            for s_idx in range(len(segments)):
                seg_win = [
                    d.get(name, float("nan"))
                    for d in (win_vals[s_idx] if s_idx < len(win_vals) else [])
                ]
                seg_win = [v for v in seg_win if math.isfinite(v)]
                oth_win: List[float] = []
                for o_idx in range(len(segments)):
                    if o_idx == s_idx:
                        continue
                    oth_win.extend(
                        d.get(name, float("nan"))
                        for d in (win_vals[o_idx] if o_idx < len(win_vals) else [])
                    )
                oth_win = [v for v in oth_win if math.isfinite(v)]
                if len(seg_win) >= 3 and len(oth_win) >= 5:
                    d_seg, lo_seg, hi_seg = bootstrap_ci_cohen_d(
                        np.asarray(oth_win),
                        np.asarray(seg_win),
                        n_boot=100,
                        seed=cfg.seed,
                    )
                    if (
                        math.isfinite(d_seg)
                        and math.isfinite(lo_seg)
                        and math.isfinite(hi_seg)
                        and (lo_seg > 0.0 or hi_seg < 0.0)
                    ):
                        infos.append(abs(d_seg))
                    else:
                        infos.append(0.0)
                else:
                    infos.append(float("nan"))

            fin_infos = [x for x in infos if math.isfinite(x)]
            peak = (
                int(np.nanargmax(np.asarray([x if math.isfinite(x) else -1.0 for x in infos])))
                if fin_infos
                else None
            )
            pre_vals = [
                vals[s]
                for s, seg in enumerate(segments)
                if seg["position"] == "pre_T0" and math.isfinite(vals[s])
            ]
            post_vals = [
                vals[s]
                for s, seg in enumerate(segments)
                if seg["position"] == "post_T0" and math.isfinite(vals[s])
            ]
            delta = float(np.mean(post_vals) - np.mean(pre_vals)) if pre_vals and post_vals else float("nan")
            sign = (
                ("up" if delta > 0.0 else ("down" if delta < 0.0 else "flat"))
                if math.isfinite(delta)
                else "unknown"
            )
            profiles[name] = {
                "values_per_segment": vals,
                "median_across_segments": med_val,
                "informativeness_per_segment": infos,
                "peak_segment": peak,
                "peak_informativeness": float(max(fin_infos)) if fin_infos else float("nan"),
                "delta_post_minus_pre": delta,
                "sign_post_minus_pre": sign,
            }

        signs = [
            pr["sign_post_minus_pre"]
            for pr in profiles.values()
            if pr["sign_post_minus_pre"] in ("up", "down")
        ]
        n_up = sum(1 for s in signs if s == "up")
        n_down = sum(1 for s in signs if s == "down")
        majority = "up" if (signs and n_up >= n_down) else ("down" if signs else "unknown")
        frac_maj = (max(n_up, n_down) / len(signs)) if signs else 0.0

        peaks = [pr["peak_segment"] for pr in profiles.values() if pr["peak_segment"] is not None]
        n_distinct_peaks = len(set(peaks)) if peaks else 0
        top_div = sorted(
            [
                (name, pr["peak_segment"], pr["peak_informativeness"])
                for name, pr in profiles.items()
                if pr["peak_segment"] is not None and math.isfinite(pr["peak_informativeness"])
            ],
            key=lambda x: x[2],
            reverse=True,
        )[:5]

        pairs: List[Dict[str, Any]] = []
        pos_map = {s: seg["position"] for s, seg in enumerate(segments)}
        for a_name, a_pr in profiles.items():
            if a_pr["peak_segment"] is None:
                continue
            if not math.isfinite(a_pr["peak_informativeness"]) or a_pr["peak_informativeness"] < 0.8:
                continue
            for b_name, b_pr in profiles.items():
                if b_name == a_name or b_pr["peak_segment"] is None:
                    continue
                if b_pr["peak_segment"] <= a_pr["peak_segment"]:
                    continue
                if not math.isfinite(b_pr["peak_informativeness"]) or b_pr["peak_informativeness"] < 0.8:
                    continue
                is_pre_post = (
                    pos_map.get(a_pr["peak_segment"]) == "pre_T0"
                    and pos_map.get(b_pr["peak_segment"]) == "post_T0"
                )
                pairs.append(
                    {
                        "estimator_a": a_name,
                        "estimator_b": b_name,
                        "peak_segment_a": int(a_pr["peak_segment"]),
                        "peak_segment_b": int(b_pr["peak_segment"]),
                        "position_a": pos_map.get(a_pr["peak_segment"]),
                        "position_b": pos_map.get(b_pr["peak_segment"]),
                        "informativeness_a": float(a_pr["peak_informativeness"]),
                        "informativeness_b": float(b_pr["peak_informativeness"]),
                        "min_informativeness": float(
                            min(a_pr["peak_informativeness"], b_pr["peak_informativeness"])
                        ),
                        "estimator_pre": a_name if is_pre_post else None,
                        "estimator_post": b_name if is_pre_post else None,
                    }
                )

        pairs = sorted(pairs, key=lambda x: x["min_informativeness"], reverse=True)[:10]
        total_pairs += len(pairs)

        per_seg_top: Dict[str, List[Dict[str, Any]]] = {}
        for s in range(len(segments)):
            cand = sorted(
                [
                    (name, pr["informativeness_per_segment"][s])
                    for name, pr in profiles.items()
                    if len(pr["informativeness_per_segment"]) > s
                    and math.isfinite(pr["informativeness_per_segment"][s])
                ],
                key=lambda x: x[1],
                reverse=True,
            )[:5]
            per_seg_top[f"segment_{s}"] = [
                {"estimator": nm, "informativeness": float(v)} for nm, v in cand
            ]

        per_flux[fname] = {
            "profiles": profiles,
            "convergence": {
                "n_up": int(n_up),
                "n_down": int(n_down),
                "majority_sign": majority,
                "fraction_majority": float(frac_maj),
                "note": "convergence is a tally, not forced consensus; divergence is also informative",
            },
            "divergence": {
                "n_distinct_peak_segments": int(n_distinct_peaks),
                "top_divergent": [
                    {"estimator": nm, "peak_segment": int(ps), "peak_informativeness": float(v)}
                    for nm, ps, v in top_div
                ],
            },
            "complementary_pairs": pairs,
            "per_segment_top": per_seg_top,
        }

    return {
        "status": "ok",
        "segments": segments,
        "per_flux": per_flux,
        "summary": {
            "n_segments": len(segments),
            "n_fluxes": len(ds.flux_names),
            "n_estimators_distinct": len(UNIQUE_ESTIMATORS),
            "n_estimator_names": len(ESTIMATORS),
            "total_complementary_pairs": int(total_pairs),
            "definition": "convergence and divergence are complementary signals; never average distinct lenses",
        },
    }


def level_universal(
    ds: UniversalDataset,
    best_scan: Dict[str, Any],
    cascade: Dict[str, Any],
    est_by_flux: Dict[str, Dict[str, float]],
    cfg: UniversalConfig,
    falsif: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Compute domain-agnostic structural levels L1..L7."""
    target, control = ds.target, ds.control
    levels: Dict[str, Any] = {}

    if best_scan.get("status") == "ok":
        d = best_scan["cohen_d"]
        direction = "up" if d > 0.05 else ("down" if d < -0.05 else "flat")
        horizon_dirs: List[float] = []
        for h in cfg.horizons:
            idx_h = int(np.clip(best_scan["idx"] + h, cfg.min_group, len(target) - cfg.min_group - 1))
            dh = cohen_d(target[:idx_h], target[idx_h:])
            if math.isfinite(dh):
                horizon_dirs.append(dh)
        stab = stability_weight(horizon_dirs)
        levels["L1_direction"] = {
            "status": "ok",
            "direction": direction,
            "cohen_d": float(d),
            "ci_low": best_scan.get("cohen_d_ci_low"),
            "ci_high": best_scan.get("cohen_d_ci_high"),
            "p_permutation": best_scan.get("p_permutation"),
            "confidence": float(stab),
            "multi_horizon": {
                "horizons": cfg.horizons,
                "cohen_d_by_horizon": horizon_dirs,
                "stability": float(stab),
            },
            "definition": "direction = sign(empirical post-pre effect). Invariant to column names.",
        }

        # L2 Magnitude: stability reflects multi-horizon consistency rather than trivial singleton 1.0
        mean_pre = best_scan.get("mean_pre", float("nan"))
        mean_post = best_scan.get("mean_post", float("nan"))
        rel_change = (
            float((mean_post - mean_pre) / (abs(mean_pre) if mean_pre != 0.0 else 1.0))
            if math.isfinite(mean_pre) and math.isfinite(mean_post)
            else float("nan")
        )
        levels["L2_magnitude"] = {
            "status": "ok",
            "stat_kind": best_scan.get("stat_kind", "mean"),
            "pre_stat": best_scan.get("pre_stat", mean_pre),
            "post_stat": best_scan.get("post_stat", mean_post),
            "abs_cohen_d": float(abs(d)),
            "mean_pre": mean_pre,
            "mean_post": mean_post,
            "relative_change": rel_change,
            "confidence": float(stab),
        }

        # L3 Regime position relative to threshold
        frac_post = float(np.mean(control > best_scan["control_value"]))
        state = "pre" if frac_post < 0.15 else ("post" if frac_post > 0.85 else "transition")
        mw_stab = (
            falsif.get("multi_window", {}).get("stability", 0.0)
            if isinstance(falsif, dict)
            else 0.0
        )
        levels["L3_regime"] = {
            "status": "ok",
            "state": state,
            "fraction_post_threshold": frac_post,
            "confidence": float(mw_stab),
        }

        # L4 Signal strength
        p_corr = best_scan.get("p_channel_adjusted", best_scan.get("p_scan_null", best_scan.get("p_permutation", float("nan"))))
        sig_level = (
            "strong"
            if abs(d) > 1.0 and p_corr is not None and math.isfinite(p_corr) and p_corr <= 0.05
            else ("moderate" if abs(d) > 0.5 else "weak")
        )
        levels["L4_signal"] = {
            "status": "ok",
            "level": sig_level,
            "abs_cohen_d": float(abs(d)),
            "null_model": best_scan.get("null_model"),
            "p_channel_raw": best_scan.get("p_channel_raw", best_scan.get("p_scan_null")),
            "p_channel_adjusted": best_scan.get("p_channel_adjusted"),
            "n_channels_family": best_scan.get("n_channels_family"),
            "p_scan_null": best_scan.get("p_scan_null"),
            "p_permutation_scan_corrected": best_scan.get("p_permutation_scan_corrected"),
            "p_permutation_local": best_scan.get("p_permutation_local"),
            "p_permutation_global": best_scan.get("p_permutation_global"),
            "definition": "signal strength = |effect| + multiplicity-adjusted null p-value; not a risk score or probability",
        }
    else:
        levels["L1_direction"] = {"status": "insufficient_data"}
        levels["L2_magnitude"] = {"status": "insufficient_data"}
        levels["L3_regime"] = {"status": "insufficient_data"}
        levels["L4_signal"] = {"status": "insufficient_data", "level": "unknown"}

    # L5 Complexity: single-pass before/after T0 dimension roughness contrast (always on default path)
    # Evaluates the 13 unique dimension estimators (same subset displayed in reports/L5 contrast).
    # L7 sliding-window interactions & predict_universal() remain behind --complexity-diagnostics.
    t0_idx: Optional[int] = None
    if best_scan.get("status") == "ok" and best_scan.get("idx") is not None:
        t0_idx = int(best_scan["idx"])

    if t0_idx is not None and t0_idx > 15 and (ds.n - t0_idx) > 15:
        left_seg = ds.target[:t0_idx]
        right_seg = ds.target[t0_idx:]
        est_left = apply_dimension_estimators(left_seg)
        est_right = apply_dimension_estimators(right_seg)
        contrast: Dict[str, Dict[str, Any]] = {}
        for name, _, is_dim in UNIQUE_ESTIMATORS:
            if not is_dim:
                continue
            vl = est_left.get(name, float("nan"))
            vr = est_right.get(name, float("nan"))
            delta = float(vr - vl) if math.isfinite(vl) and math.isfinite(vr) else float("nan")
            contrast[name] = {
                "value_left": float(vl),
                "value_right": float(vr),
                "delta": delta,
                "is_dimension_estimator": True,
            }
        dim_deltas = [v["delta"] for v in contrast.values() if math.isfinite(v["delta"])]
        levels["L5_complexity"] = {
            "status": "ok",
            "exploratory": False,
            "mode": "single_pass_contrast",
            "t0_idx": t0_idx,
            "n_left": len(left_seg),
            "n_right": len(right_seg),
            "n_estimators_evaluated": len(contrast),
            "n_dimension_estimators_finite": len(dim_deltas),
            "contrast": contrast,
            "note": "Single-pass dimension roughness description around T0; does not vote in grade_evidence()",
        }
    else:
        levels["L5_complexity"] = {
            "status": "insufficient_data",
            "exploratory": False,
            "mode": "single_pass_contrast",
            "n_estimators_evaluated": 0,
            "note": "T0 not available or segments too short for roughness contrast",
        }

    if not getattr(cfg, "run_complexity_diagnostics", False):
        levels["L6_prediction"] = {
            "status": "disabled_in_core",
            "note": "prediction lives outside analyze() inside predict_universal() and stays locked unless criteria (including L7 exploratory run) pass",
        }
        levels["L7_interactions"] = {
            "status": "disabled_by_default",
            "exploratory": True,
            "segments": [],
            "per_flux": {},
            "summary": {
                "n_segments": 0,
                "n_fluxes": 0,
                "total_complementary_pairs": 0,
                "note": "Exploratory L7 sliding-window interactions disabled on default path; pass run_complexity_diagnostics=True",
            },
        }
        return levels

    # Preserve single-pass contrast computed above for merging into exploratory L5
    l5_contrast_data = levels.get("L5_complexity", {}).get("contrast")
    l5_n_left = levels.get("L5_complexity", {}).get("n_left")
    l5_n_right = levels.get("L5_complexity", {}).get("n_right")
    l5_n_dim_finite = levels.get("L5_complexity", {}).get("n_dimension_estimators_finite", 0)

    all_est: List[float] = []
    for est in est_by_flux.values():
        if isinstance(est, dict):
            all_est.extend(v for v in est.values() if isinstance(v, (int, float)) and math.isfinite(v))

    tlog = compute_tlog(
        est_by_flux.get(ds.target_name, {}) if isinstance(est_by_flux.get(ds.target_name), dict) else {},
        ds.n,
        series=ds.target,
        n_perm=25,
        seed=cfg.seed + 505,
    )
    alerts: List[str] = []
    if (
        tlog.get("calibrated")
        and math.isfinite(tlog.get("z_score", float("nan")))
        and abs(tlog["z_score"]) > 2.0
        and tlog.get("p_permutation", 1.0) <= 0.10
    ):
        alerts.append("t_log_deviates_from_permutation_null")

    levels["L5_complexity"] = {
        "status": "ok",
        "exploratory": True,
        "mode": "full_exploratory",
        "t_log": tlog,
        "n_estimators_evaluated": len(ESTIMATORS),
        "n_unique_estimators": len(UNIQUE_ESTIMATORS),
        "alerts": alerts,
        "confidence": float(stability_weight(all_est) if all_est else 0.0),
        "note": "Exploratory complexity diagnostic only (opt-in via run_complexity_diagnostics=True); never proof of a threshold",
    }
    if l5_contrast_data is not None:
        levels["L5_complexity"]["contrast"] = l5_contrast_data
        levels["L5_complexity"]["n_left"] = l5_n_left
        levels["L5_complexity"]["n_right"] = l5_n_right
        levels["L5_complexity"]["n_dimension_estimators_finite"] = l5_n_dim_finite

    # L6 Prediction disabled in core analysis
    levels["L6_prediction"] = {
        "status": "disabled_in_core",
        "note": "prediction lives outside analyze() inside predict_universal() and stays locked unless criteria pass",
    }

    # L7 Interactions (exploratory opt-in)
    try:
        l7_res = compute_interactions(ds, cascade, cfg)
        if isinstance(l7_res, dict):
            l7_res["exploratory"] = True
        levels["L7_interactions"] = l7_res
    except Exception as exc:
        levels["L7_interactions"] = {"status": "error", "exploratory": True, "error": str(exc)}

    return levels

