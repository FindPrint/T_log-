def _simulate_ar1(n: int, phi: float, sigma: float, rng: np.random.Generator) -> np.ndarray:
    """Simulate a stationary Gaussian AR(1) series with matched lag-1 autocorrelation."""
    x = np.empty(n, dtype=float)
    denom = math.sqrt(max(1.0 - phi * phi, 0.05))
    x[0] = rng.normal(0.0, sigma / denom)
    eps = rng.normal(0.0, sigma, size=n)
    for i in range(1, n):
        x[i] = phi * x[i - 1] + eps[i]
    return x


def _simulate_arima110(n: int, phi_dy: float, rng: np.random.Generator) -> np.ndarray:
    """Simulate an integrated ARIMA(1,1,0) smooth momentum series matching delta autocorrelation."""
    burn = 50
    dy = np.zeros(n + burn, dtype=float)
    eps = rng.normal(0.0, 1.0, size=n + burn)
    p = max(-0.90, min(0.90, float(phi_dy)))
    for i in range(1, n + burn):
        dy[i] = p * dy[i - 1] + eps[i]
    return np.cumsum(dy[burn:])


def _local_linear_at_cut(
    y: np.ndarray,
    idx: int,
    w: int,
    detector: str,
) -> float:
    """Evaluate exact matched slope_break or detrended_jump effect metric at a fixed cut."""
    if idx < w or idx + w > len(y) or w < 4:
        return float("nan")
    t_arr = np.arange(w, dtype=float)
    tc = t_arr - float(np.mean(t_arr))
    denom = float(np.sum(tc * tc))
    yl = y[idx - w : idx]
    yr = y[idx : idx + w]
    if denom <= 0.0:
        return float("nan")
    bl = float(np.sum(tc * (yl - np.mean(yl))) / denom)
    br = float(np.sum(tc * (yr - np.mean(yr))) / denom)
    al = float(np.mean(yl)) - bl * float(np.mean(t_arr))
    ar = float(np.mean(yr)) - br * float(np.mean(t_arr))
    sse = float(np.sum((yl - (al + bl * t_arr)) ** 2) + np.sum((yr - (ar + br * t_arr)) ** 2))
    sd = math.sqrt(max(sse / max(2 * w - 4, 1), 1e-18))
    if detector == "slope_break":
        se = sd * math.sqrt(2.0 / denom)
        return float(((br - bl) / max(se, 1e-18)) / math.sqrt(w))
    return float((ar - (al + bl * w)) / sd)


def _scan_active_channel(
    ctrl: np.ndarray,
    y: np.ndarray,
    detector: str,
    window: int,
    min_group: int,
    seed: int,
    n_boot: int = 20,
    n_perm: int = 50,
    compute_scan_p: bool = True,
    n_scan_perm: int = 200,
) -> Dict[str, Any]:
    """Run threshold scan matched to the active detector family (symmetrized falsification null)."""
    y_arr = np.asarray(y, dtype=float)
    x_arr = np.asarray(ctrl, dtype=float)
    n = len(y_arr)
    if detector == "slope_break":
        w_s = int(max(8, min(window, n // 3)))
        if n < 2 * w_s + 2 or not np.all(np.isfinite(y_arr)):
            return {"status": "insufficient_data", "cohen_d": float("nan"), "p_permutation_scan_corrected": float("nan")}
        idx_s, _, ts = _local_linear_stats_vec(y_arr, w_s)
        if len(ts) == 0:
            return {"status": "no_finite_threshold", "cohen_d": float("nan"), "p_permutation_scan_corrected": float("nan")}
        pos = int(np.argmax(np.abs(ts)))
        best_i = int(idx_s[pos])
        best_d = float(ts[pos] / math.sqrt(w_s))
        p_corr = float("nan")
        if compute_scan_p:
            t_idx = np.arange(n, dtype=float)
            res_s = y_arr - np.polyval(np.polyfit(t_idx, y_arr, 1), t_idx)
            bl_s = int(max(2, min(8, w_s // 4)))
            rng = np.random.default_rng(seed)
            null_max: List[float] = []
            for _ in range(max(10, int(n_scan_perm))):
                rb = _block_permute(res_s, bl_s, rng)
                _, _, sim_ts = _local_linear_stats_vec(rb, w_s)
                if len(sim_ts):
                    null_max.append(float(np.max(np.abs(sim_ts))) / math.sqrt(w_s))
            if null_max:
                p_corr = (1.0 + float(np.sum(np.asarray(null_max) >= abs(best_d)))) / (len(null_max) + 1.0)
        return {
            "status": "ok",
            "idx": best_i,
            "control_value": float(x_arr[best_i]),
            "cohen_d": best_d,
            "p_permutation_scan_corrected": float(p_corr),
            "p_permutation_local": float(p_corr),
        }

    if detector == "detrended_jump":
        w_j = int(max(6, min(window, n // 3)))
        if n < 2 * w_j + 2 or not np.all(np.isfinite(y_arr)):
            return {"status": "insufficient_data", "cohen_d": float("nan"), "p_permutation_scan_corrected": float("nan")}
        idx_j, dj, _ = _local_linear_stats_vec(y_arr, w_j)
        if len(dj) == 0:
            return {"status": "no_finite_threshold", "cohen_d": float("nan"), "p_permutation_scan_corrected": float("nan")}
        pos = int(np.argmax(np.abs(dj)))
        best_i = int(idx_j[pos])
        best_d = float(dj[pos])
        p_corr = float("nan")
        if compute_scan_p:
            t_idx = np.arange(n, dtype=float)
            deg_j = min(3, max(1, n // 30))
            base_j = np.polyval(np.polyfit(t_idx, y_arr, deg_j), t_idx)
            res_j = y_arr - base_j
            bl_j = int(max(2, min(8, w_j // 4)))
            rng = np.random.default_rng(seed)
            null_max = []
            for _ in range(max(10, int(n_scan_perm))):
                rb = _block_permute(res_j, bl_j, rng)
                _, sim_dj, _ = _local_linear_stats_vec(base_j + rb, w_j)
                if len(sim_dj):
                    null_max.append(float(np.max(np.abs(sim_dj))))
            if null_max:
                p_corr = (1.0 + float(np.sum(np.asarray(null_max) >= abs(best_d)))) / (len(null_max) + 1.0)
        return {
            "status": "ok",
            "idx": best_i,
            "control_value": float(x_arr[best_i]),
            "cohen_d": best_d,
            "p_permutation_scan_corrected": float(p_corr),
            "p_permutation_local": float(p_corr),
        }

    return scan_threshold(
        x_arr,
        y_arr,
        window=window,
        min_group=min_group,
        n_boot=n_boot,
        n_perm=n_perm,
        seed=seed,
        compute_scan_p=compute_scan_p,
        n_scan_perm=n_scan_perm,
    )


def falsification_suite(
    ds: UniversalDataset,
    best_scan: Dict[str, Any],
    cfg: UniversalConfig,
) -> Dict[str, Any]:
    """Run rigorous falsification checks against multiple null hypotheses (P5).

    Fixes over v7.1.5:
    - All null scans use the EXACT same primary window ``w_primary`` as ``best_scan``.
    - Independent RNG streams per test (no cross-dataset identical white-noise artifacts).
    - Adds ``ar1_surrogate_null`` so pure random walks / smooth seasonal waves cannot
      masquerade as sharp regime breaks against an i.i.d. permutation null.
    - Tightens ``multi_window`` stability to penalize drift relative to ``0.20 * ptp(control)``.
    """
    target, control = ds.target, ds.control
    idx = best_scan.get("idx") if best_scan.get("status") == "ok" else None
    w_primary = int(
        best_scan.get("window_used")
        or (cfg.window_sizes[0] if cfg.window_sizes else 80)
    )
    n_scan_perm = int(getattr(cfg, "n_scan_permutations", 200))
    rng = np.random.default_rng(cfg.seed)
    out: Dict[str, Any] = {}

    detector = best_scan.get("detector", "level_shift")
    if detector == "volatility_shift" and len(target) >= 4:
        active_target = _volatility_deviation_series(np.asarray(target, dtype=float))
        active_control = np.asarray(control, dtype=float)[1:]
        active_idx = (
            int(max(0, min(len(active_target) - 1, int(idx) - 1)))
            if idx is not None
            else None
        )
    elif detector == "deseasonalized_shift" and len(target) >= 24:
        des = _deseasonalize_fft_dominant(np.asarray(target, dtype=float))
        active_target = des[0] if des is not None else np.asarray(target, dtype=float)
        active_control = np.asarray(control, dtype=float)
        active_idx = idx
    else:
        active_target = np.asarray(target, dtype=float)
        active_control = np.asarray(control, dtype=float)
        active_idx = idx

    # 1. Permuted control / target at fixed split (matched to active detector statistic)
    if active_idx is not None:
        w_eff_cut = int(max(8 if detector == "slope_break" else 6, min(w_primary, len(active_target) // 3)))
        perm_controls: List[float] = []
        for _ in range(30):
            perm_idx = rng.permutation(len(active_target))
            target_perm = active_target[perm_idx]
            if detector in ("slope_break", "detrended_jump"):
                d_p = abs(_local_linear_at_cut(target_perm, int(active_idx), w_eff_cut, detector))
            else:
                d_p = abs(cohen_d(target_perm[:active_idx], target_perm[active_idx:]))
            if math.isfinite(d_p):
                perm_controls.append(d_p)
        out["permuted_control_same_cut"] = {
            "note": "target permuted at fixed cut: |d| must collapse if split reflects real ordering",
            "d_observed": float(best_scan["cohen_d"]),
            "d_permuted_median": float(np.median(perm_controls)) if perm_controls else float("nan"),
        }

    # 2. Monotonic trend diagnostic (Spearman) on the ACTIVE detector series (P0.2 fix)
    #    The relevant series depends on the detector: deseasonalized target for
    #    deseasonalized_shift, volatility-deviation series for volatility_shift, raw otherwise.
    #    Using the raw target here missed strong monotone trends hidden by a seasonal cycle
    #    (e.g. monthly sea ice: raw rho ~ -0.22 but deseasonalized rho ~ -0.89).
    try:
        rho_active = float(
            pd.Series(active_control).corr(pd.Series(active_target), method="spearman")
        )
    except Exception:
        rho_active = float("nan")
    try:
        rho_raw = float(pd.Series(control).corr(pd.Series(target), method="spearman"))
    except Exception:
        rho_raw = float("nan")
    if best_scan.get("status") == "ok":
        best_scan["monotonicity_rho_active"] = rho_active
        best_scan["monotonicity_rho_raw"] = rho_raw
    out["trend_spearman"] = {
        "rho_control_target": rho_active,
        "rho_raw_target": rho_raw,
        "active_series": detector,
        "note": (
            "rho computed on the detector's active target (deseasonalized/volatility when "
            "applicable); |rho| >= 0.85 caps level_shift at C and shape detectors at B"
        ),
    }

    # 3. White-noise null matched to active detector statistic & window
    hash_salt = int(ds.source_hash[:8], 16) if ds.source_hash else 0
    rng_wn = np.random.default_rng(np.random.SeedSequence([int(cfg.seed), 101, hash_salt]))
    std_t = float(np.std(active_target)) if float(np.std(active_target)) > 0.0 else 1.0
    white = rng_wn.normal(float(np.mean(active_target)), std_t, size=len(active_target))
    w_scan = _scan_active_channel(
        active_control,
        white,
        detector=detector,
        window=w_primary,
        min_group=cfg.min_group,
        seed=cfg.seed + 1,
        n_boot=20,
        n_perm=50,
        compute_scan_p=True,
        n_scan_perm=n_scan_perm,
    )
    out["white_noise_null"] = {
        "cohen_d": _safe_float(w_scan.get("cohen_d")),
        "p_permutation": _safe_float(w_scan.get("p_permutation_scan_corrected")),
        "p_permutation_local": _safe_float(w_scan.get("p_permutation_local")),
        "detector_matched": detector,
        "window_used": w_primary,
        "expected": "high corrected p and low |d|; otherwise detector invents spurious breaks",
    }

    # 4. Shuffled-target null matched to active detector statistic & window
    rng_sh = np.random.default_rng(np.random.SeedSequence([int(cfg.seed), 202, hash_salt]))
    shuffled = rng_sh.permutation(active_target)
    s_scan = _scan_active_channel(
        active_control,
        shuffled,
        detector=detector,
        window=w_primary,
        min_group=cfg.min_group,
        seed=cfg.seed + 2,
        n_boot=20,
        n_perm=50,
        compute_scan_p=True,
        n_scan_perm=n_scan_perm,
    )
    out["shuffled_target_null"] = {
        "cohen_d": _safe_float(s_scan.get("cohen_d")),
        "p_permutation": _safe_float(s_scan.get("p_permutation_scan_corrected")),
        "p_permutation_local": _safe_float(s_scan.get("p_permutation_local")),
        "detector_matched": detector,
        "window_used": w_primary,
    }

    # 5. Autocorrelated surrogate null (AR(1), or integrated ARIMA(1,1,0) for smooth momentum)
    if active_idx is not None:
        phi_within = within_regime_ar1(active_target, int(active_idx))
        dy = np.diff(active_target)
        phi_dy = 0.0
        if len(dy) >= 10 and np.std(dy) > 0.0:
            phi_dy = float(np.corrcoef(dy[:-1], dy[1:])[0, 1])
            if not math.isfinite(phi_dy):
                phi_dy = 0.0
        use_arima = (phi_within >= 0.75) and (phi_dy >= 0.25)
        surrogate_model = "arima_1_1_0" if use_arima else "ar1"
        phi_sim = (
            float(phi_dy)
            if use_arima
            else (max(phi_within, 0.98) if (phi_within >= 0.80 and abs(phi_dy) < 0.25) else phi_within)
        )
        stat_name = "abs_t_stat" if detector == "slope_break" else ("abs_effect_d" if detector == "detrended_jump" else "abs_cohen_d")
        obs_stat = (
            abs(float(best_scan.get("t_stat", 0.0)))
            if detector == "slope_break"
            else abs(float(best_scan.get("cohen_d", 0.0)))
        )
        n_ar_perm = min(200, max(50, n_scan_perm))
        rng_ar = np.random.default_rng(np.random.SeedSequence([int(cfg.seed), 303, hash_salt]))
        ar_max: List[float] = []
        w_eff = int(max(8 if detector == "slope_break" else 6, min(w_primary, len(active_target) // 3)))
        for _ in range(n_ar_perm):
            sim = (
                _simulate_arima110(len(active_target), phi_dy, rng_ar)
                if use_arima
                else _simulate_ar1(len(active_target), phi_sim, 1.0, rng_ar)
            )
            if detector == "slope_break":
                _, _, ts_sim = _local_linear_stats_vec(sim, w_eff)
                v_sim = float(np.max(np.abs(ts_sim))) if len(ts_sim) else float("nan")
            elif detector == "detrended_jump":
                _, dj_sim, _ = _local_linear_stats_vec(sim, w_eff)
                v_sim = float(np.max(np.abs(dj_sim))) if len(dj_sim) else float("nan")
            else:
                d_sim, _ = _scan_max_d(active_control, sim, window=w_primary, min_group=cfg.min_group)
                v_sim = abs(d_sim) if math.isfinite(d_sim) else float("nan")
            if math.isfinite(v_sim):
                ar_max.append(v_sim)
        p_ar1 = (
            (1.0 + float(np.sum(np.asarray(ar_max) >= obs_stat))) / (len(ar_max) + 1.0)
            if ar_max
            else float("nan")
        )
        out["ar1_surrogate_null"] = {
            "phi_within": float(phi_within),
            "phi_diff1": float(phi_dy),
            "phi_simulated": float(phi_sim),
            "surrogate_model": surrogate_model,
            "statistic_tested": stat_name,
            "observed_stat": float(obs_stat),
            "p_ar1_scan_corrected": float(p_ar1),
            "ar1_null_p95": float(np.percentile(ar_max, 95)) if ar_max else float("nan"),
            "ar1_null_p95_abs_d": float(np.percentile(ar_max, 95)) if ar_max else float("nan"),
            "note": f"tests whether observed scan statistic exceeds a matched {surrogate_model.upper()} surrogate without break",
        }

    # 6. Split-half diagnostic matched to active detector (same relative window proportion)
    half = len(active_target) // 2
    w_half = max(cfg.min_group, min(w_primary, max(cfg.min_group, half // 3)))
    h1 = _scan_active_channel(
        active_control[:half],
        active_target[:half],
        detector=detector,
        window=w_half,
        min_group=cfg.min_group,
        seed=cfg.seed + 3,
        n_boot=20,
        n_perm=50,
        compute_scan_p=True,
        n_scan_perm=min(100, n_scan_perm),
    )
    h2 = _scan_active_channel(
        active_control[half:],
        active_target[half:],
        detector=detector,
        window=w_half,
        min_group=cfg.min_group,
        seed=cfg.seed + 4,
        n_boot=20,
        n_perm=50,
        compute_scan_p=True,
        n_scan_perm=min(100, n_scan_perm),
    )
    d1 = _safe_float(h1.get("cohen_d"))
    d2 = _safe_float(h2.get("cohen_d"))
    p1_h = _safe_float(h1.get("p_permutation_scan_corrected"))
    p2_h = _safe_float(h2.get("p_permutation_scan_corrected"))
    opposite_sig = (
        math.isfinite(d1)
        and math.isfinite(d2)
        and (d1 * d2 < 0.0)
        and math.isfinite(p1_h)
        and math.isfinite(p2_h)
        and p1_h <= 0.05
        and p2_h <= 0.05
    )
    out["split_half"] = {
        "half1_idx": h1.get("idx"),
        "half1_d": d1,
        "half1_p_scan_corrected": p1_h,
        "half2_idx": h2.get("idx"),
        "half2_d": d2,
        "half2_p_scan_corrected": p2_h,
        "opposite_significant_halves": bool(opposite_sig),
        "agreement": "opposite strong splits in both halves suggest wandering/non-stationary drift rather than one stable threshold",
    }

    # 7. Multi-window stability (penalized wrt 20% of control span so random picks don't score 0.9+)
    scans: List[float] = []
    for w in cfg.window_sizes:
        if detector == "detrended_jump" and np.all(np.isfinite(target)) and len(target) >= 2 * max(6, w) + 2:
            w_eff = int(max(6, min(w, len(target) // 3)))
            idx_j, dj, _ = _local_linear_stats_vec(np.asarray(target, dtype=float), w_eff)
            if len(dj):
                best_i = int(idx_j[int(np.argmax(np.abs(dj)))])
                scans.append(float(control[best_i]))
        elif detector == "slope_break" and np.all(np.isfinite(target)) and len(target) >= 2 * max(8, w) + 2:
            w_eff = int(max(8, min(w, len(target) // 3)))
            idx_s, _, ts = _local_linear_stats_vec(np.asarray(target, dtype=float), w_eff)
            if len(ts):
                best_is = int(idx_s[int(np.argmax(np.abs(ts)))])
                scans.append(float(control[best_is]))
        else:
            s = scan_threshold(
                active_control,
                active_target,
                window=w,
                min_group=cfg.min_group,
                n_boot=20,
                n_perm=50,
                seed=cfg.seed,
                compute_scan_p=False,
            )
            if s.get("status") == "ok":
                scans.append(float(s["control_value"]))
    ctrl_span = float(np.ptp(control)) if float(np.ptp(control)) > 0.0 else 1.0
    if len(scans) >= 2:
        stab = max(0.0, 1.0 - float(np.std(scans)) / (0.20 * ctrl_span))
    else:
        stab = 0.0
    out["multi_window"] = {
        "threshold_values": scans,
        "std_thresholds": float(np.std(scans)) if len(scans) >= 2 else float("nan"),
        "stability": float(stab),
        "n_windows": len(scans),
        "note": (
            "single valid window = stability NOT proven (0.0)"
            if len(scans) < 2
            else "stability measured against 20% of control span"
        ),
    }

    # 8. Multi-seed permutation stability
    ps = [
        permutation_p_value(active_target[:active_idx], active_target[active_idx:], n_perm=100, seed=cfg.seed + i)
        if active_idx is not None
        else float("nan")
        for i in range(5)
    ]
    out["multi_seed_p"] = {
        "p_values": ps,
        "p_max": float(np.nanmax(ps)) if len(ps) else float("nan"),
    }

    # 9. Optional harmonic ablation test (P4)
    if cfg.harmonic_ablation and idx is not None:
        harm_ds: List[float] = []
        for trial in range(10):
            r = np.random.default_rng(cfg.seed + 100 + trial)
            mask = r.random(len(target)) < cfg.harmonic_prob
            jitter = np.zeros_like(target)
            scale_j = 0.05 * std_t * (PHI if trial % 2 == 0 else PI)
            jitter[mask] = r.normal(0.0, scale_j, size=int(np.sum(mask)))
            hs = scan_threshold(
                control,
                target + jitter,
                window=w_primary,
                min_group=cfg.min_group,
                n_boot=20,
                n_perm=50,
                seed=cfg.seed + 100 + trial,
                compute_scan_p=False,
            )
            harm_ds.append(_safe_float(hs.get("cohen_d")))
        out["harmonic_ablation"] = {
            "cohen_d_with_harmonic_jitter_median": float(np.nanmedian(harm_ds))
            if harm_ds
            else float("nan"),
            "cohen_d_observed": float(best_scan["cohen_d"]),
            "interpretation": "if median collapses under mild perturbation, reject threshold",
        }

    return out


def walk_forward(
    ds: UniversalDataset,
    best_scan: Dict[str, Any],
    cfg: UniversalConfig,
    n_splits: int = 5,
) -> Dict[str, Any]:
    """Honest walk-forward validation counting abstentions explicitly.

    Trains threshold on past prefix ``[:train_end]``, evaluates on future block
    ``[edges[s+1]:edges[s+2]]`` using consistent effect scales matching the active detector.
    """
    if best_scan.get("status") != "ok":
        return {"status": "no_threshold"}

    detector = best_scan.get("detector", "level_shift")
    n = ds.n
    edges = np.linspace(0, n, n_splits + 1).astype(int)
    successes, trials, abstentions = 0, 0, 0
    details: List[Dict[str, Any]] = []
    w_primary = int(
        best_scan.get("window_used")
        or (cfg.window_sizes[0] if cfg.window_sizes else 80)
    )

    if detector == "slope_break":
        for s in range(n_splits - 1):
            train_end = int(edges[s + 1])
            test_a, test_b = int(edges[s + 1]), int(edges[s + 2])
            if test_b - test_a < 8 or train_end < 2 * max(8, cfg.min_group) + 4:
                continue
            w_tr = max(8, min(w_primary, train_end // 3))
            idx_s, _, ts = _local_linear_stats_vec(ds.target[:train_end], w_tr)
            if len(ts) == 0:
                continue
            pos = int(np.argmax(np.abs(ts)))
            t_max = float(ts[pos])
            if abs(t_max) < 3.0:
                abstentions += 1
                details.append({"split": s, "abstained": True, "t_train": t_max})
                continue
            cut_tr = int(idx_s[pos])
            t_pre = np.arange(cut_tr, dtype=float)
            t_post = np.arange(train_end - cut_tr, dtype=float)
            if len(t_pre) < 4 or len(t_post) < 4:
                continue
            b_pre = float(np.polyfit(t_pre, ds.target[:cut_tr], 1)[0])
            b_post = float(np.polyfit(t_post, ds.target[cut_tr:train_end], 1)[0])
            b_test = float(np.polyfit(np.arange(test_b - test_a, dtype=float), ds.target[test_a:test_b], 1)[0])
            ok = abs(b_test - b_post) < abs(b_test - b_pre)
            successes += int(ok)
            trials += 1
            details.append(
                {
                    "split": s,
                    "b_pre": b_pre,
                    "b_post": b_post,
                    "b_test": b_test,
                    "success": bool(ok),
                    "case": "slope_continuation",
                }
            )
    else:
        if detector == "volatility_shift" and len(ds.target) >= 4:
            wf_y = _volatility_deviation_series(ds.target)
            wf_ctrl = ds.control[1:]
        elif detector == "deseasonalized_shift" and len(ds.target) >= 24:
            des = _deseasonalize_fft_dominant(ds.target)
            wf_y = des[0] if des is not None else ds.target
            wf_ctrl = ds.control
        else:
            wf_y = ds.target
            wf_ctrl = ds.control
        wf_n = len(wf_y)
        edges = np.linspace(0, wf_n, n_splits + 1).astype(int)

        for s in range(n_splits - 1):
            train_end = int(edges[s + 1])
            if train_end < 2 * cfg.min_group + 4:
                continue
            if detector == "detrended_jump":
                w_tr = max(6, min(w_primary, train_end // 3))
                idx_j, dj, _ = _local_linear_stats_vec(wf_y[:train_end], w_tr)
                if len(dj) == 0:
                    continue
                pos = int(np.argmax(np.abs(dj)))
                d_train = float(dj[pos])
                if abs(d_train) < 2.0:
                    abstentions += 1
                    details.append({"split": s, "abstained": True, "d_train": d_train})
                    continue
                cut_tr = int(idx_j[pos])
                thr = float(wf_ctrl[cut_tr])
                train_scan = {"status": "ok", "control_value": thr, "cohen_d": d_train}
            else:
                train_scan = scan_threshold(
                    wf_ctrl[:train_end],
                    wf_y[:train_end],
                    window=w_primary,
                    min_group=cfg.min_group,
                    n_boot=20,
                    n_perm=50,
                    seed=cfg.seed + s,
                    compute_scan_p=False,
                )
                if train_scan.get("status") != "ok":
                    continue
                if abs(train_scan.get("cohen_d", 0.0)) < 0.5:
                    abstentions += 1
                    details.append(
                        {
                            "split": s,
                            "abstained": True,
                            "d_train": float(train_scan.get("cohen_d", 0.0)),
                        }
                    )
                    continue

            thr = float(train_scan["control_value"])
            d_train = float(train_scan["cohen_d"])
            test_a, test_b = int(edges[s + 1]), int(edges[s + 2])
            if test_b - test_a < 8:
                continue

            test_ctrl, test_y = wf_ctrl[test_a:test_b], wf_y[test_a:test_b]
            train_ctrl, train_y = wf_ctrl[:train_end], wf_y[:train_end]
            train_pre = train_y[train_ctrl <= thr]
            train_post = train_y[train_ctrl > thr]
            mask_post = test_ctrl > thr

            if int(np.sum(mask_post)) >= 4 and int(np.sum(~mask_post)) >= 4:
                d_test = cohen_d(test_y[~mask_post], test_y[mask_post])
                ok = math.isfinite(d_test) and (d_test * d_train > 0.0) and abs(d_test) > 0.5
                successes += int(ok)
                trials += 1
                details.append(
                    {
                        "split": s,
                        "d_train": d_train,
                        "d_test": float(d_test),
                        "success": bool(ok),
                        "case": "both_sides",
                    }
                )
            elif int(np.sum(mask_post)) >= 4:
                if len(train_pre) < 4 or len(train_post) < 4:
                    continue
                d_vs_pre = cohen_d(train_pre, test_y)
                d_vs_post = cohen_d(train_post, test_y)
                ok = (
                    math.isfinite(d_vs_pre)
                    and math.isfinite(d_vs_post)
                    and abs(d_vs_post) < abs(d_vs_pre)
                    and abs(d_vs_pre) > 0.5
                )
                successes += int(ok)
                trials += 1
                details.append(
                    {
                        "split": s,
                        "d_train": d_train,
                        "d_test_future_vs_pre": float(d_vs_pre),
                        "d_test_future_vs_post": float(d_vs_post),
                        "success": bool(ok),
                        "case": "future_all_post",
                    }
                )
            elif int(np.sum(~mask_post)) >= 4:
                if len(train_pre) < 4 or len(train_post) < 4:
                    continue
                d_vs_pre = cohen_d(train_pre, test_y)
                d_vs_post = cohen_d(train_post, test_y)
                ok = (
                    math.isfinite(d_vs_pre)
                    and math.isfinite(d_vs_post)
                    and abs(d_vs_pre) < abs(d_vs_post)
                    and abs(d_vs_post) > 0.5
                )
                successes += int(ok)
                trials += 1
                details.append(
                    {
                        "split": s,
                        "d_train": d_train,
                        "d_test_future_vs_pre": float(d_vs_pre),
                        "d_test_future_vs_post": float(d_vs_post),
                        "success": bool(ok),
                        "case": "future_all_pre",
                    }
                )

    total = trials + abstentions
    if trials == 0:
        return {
            "status": "insufficient_splits",
            "mean_precision": 0.0,
            "mean_recall": 0.0,
            "mean_f1": 0.0,
            "mean_f1_conservative": 0.0,
            "n_splits_used": 0,
            "n_abstentions": int(abstentions),
            "n_splits_total": int(total),
            "successes": 0,
            "details": details,
        }

    f1 = successes / trials
    f1_cons = successes / total if total > 0 else 0.0
    return {
        "status": "ok",
        "mean_precision": float(f1),
        "mean_recall": float(f1),
        "mean_f1": float(f1),
        "mean_f1_conservative": float(f1_cons),
        "n_splits_used": int(trials),
        "n_abstentions": int(abstentions),
        "n_splits_total": int(total),
        "successes": int(successes),
        "details": details,
    }


def grade_evidence(
    best_scan: Dict[str, Any],
    falsif: Dict[str, Any],
    wf: Dict[str, Any],
    cfg: UniversalConfig,
) -> Dict[str, Any]:
    """Assign conservative evidence grade A/B/C/D for threshold existence (never prediction proof)."""
    rules = cfg.grade_rules
    if best_scan.get("status") != "ok":
        return {
            "grade": "D",
            "verdict": "no evidence — no finite threshold found",
            "reasons": ["scan produced no finite threshold"],
            "checks": {},
            "n_checks_passed": 0,
        }

    reasons: List[str] = []
    detector = best_scan.get("detector", "level_shift")

    ok_d = abs(best_scan["cohen_d"]) >= rules["min_cohen_d"]
    p_perm = best_scan.get("p_channel_adjusted", best_scan.get("p_scan_null"))
    null_model = str(best_scan.get("null_model", "target_permutation_scan"))
    n_fam = best_scan.get("n_channels_family")
    p_desc = (
        f"p[{null_model}; holm_m={n_fam}]"
        if (isinstance(n_fam, int) and n_fam > 1 and best_scan.get("p_channel_adjusted") is not None)
        else f"p[{null_model}]"
    )
    ok_p = p_perm is not None and math.isfinite(p_perm) and p_perm <= rules["max_p_perm"]

    stab = falsif.get("multi_window", {}).get("stability", 0.0)
    ok_stab = stab >= rules["min_stability"]

    wf_f1 = wf.get("mean_f1", 0.0) if isinstance(wf, dict) else 0.0
    wf_votes = wf.get("n_splits_used", 0) if isinstance(wf, dict) else 0
    ok_wf = (wf_f1 >= rules["min_walkforward_f1"]) and (wf_votes >= 2)

    if not ok_d:
        reasons.append(f"|effect_d|={abs(best_scan['cohen_d']):.2f} < {rules['min_cohen_d']}")
    if not ok_p:
        reasons.append(f"{p_desc}={p_perm} > {rules['max_p_perm']}")
    if not ok_stab:
        reasons.append(f"multi-window stability={stab:.2f} < {rules['min_stability']}")
    if not ok_wf:
        if wf_votes < 2:
            abst = wf.get("n_abstentions", 0) if isinstance(wf, dict) else 0
            reasons.append(f"walk-forward: only {wf_votes} voted split(s), need >= 2 (abstentions={abst})")
        else:
            reasons.append(f"walk-forward F1={wf_f1:.2f} < {rules['min_walkforward_f1']}")

    # White noise null check
    wn = falsif.get("white_noise_null", {})
    ok_white = True
    if math.isfinite(wn.get("cohen_d", float("nan"))) and math.isfinite(best_scan.get("cohen_d", float("nan"))):
        ok_white = abs(wn["cohen_d"]) < 0.5 * abs(best_scan["cohen_d"])
        if not ok_white:
            reasons.append("white-noise null achieved comparable |d| — non-specific detector")

    # Permuted control at fixed cut check
    pc = falsif.get("permuted_control_same_cut", {})
    ok_perm_ctrl = True
    if math.isfinite(pc.get("d_permuted_median", float("nan"))):
        ok_perm_ctrl = abs(pc["d_permuted_median"]) < 0.5 * abs(best_scan["cohen_d"])
        if not ok_perm_ctrl:
            reasons.append("permuted control did not collapse effect size")

    # Shuffled target null check
    sh = falsif.get("shuffled_target_null", {})
    ok_shuffled = True
    if math.isfinite(sh.get("cohen_d", float("nan"))):
        ok_shuffled = abs(sh["cohen_d"]) < 0.5 * abs(best_scan["cohen_d"])
        if not ok_shuffled:
            reasons.append("shuffled-target null produced comparable |d|")

    # Autocorrelated surrogate null check across ALL detectors and trends (AR(1) or ARIMA(1,1,0))
    rho = falsif.get("trend_spearman", {}).get("rho_control_target", float("nan"))
    is_strong_monotone = math.isfinite(rho) and abs(rho) >= 0.85
    ar1 = falsif.get("ar1_surrogate_null", {})
    ok_ar1 = True
    p_ar1 = ar1.get("p_ar1_scan_corrected", float("nan"))
    if math.isfinite(p_ar1):
        phi_sim = float(ar1.get("phi_simulated", 0.0))
        phi_within_ar = float(ar1.get("phi_within", phi_sim))
        surr_model = str(ar1.get("surrogate_model", "ar1"))
        triggered = (phi_within_ar >= 0.65) or (phi_sim >= 0.65) or (surr_model == "arima_1_1_0")
        if triggered and p_ar1 > rules["max_p_perm"]:
            ok_ar1 = False
            reasons.append(
                f"{surr_model.upper()} surrogate null failed ({detector}, phi={phi_sim:.2f}, p_ar1={p_ar1:.3f} > {rules['max_p_perm']}) — break may be autocorrelation/random-walk artifact"
            )

    # Split-half opposite significant signs check
    shalf = falsif.get("split_half", {})
    opp_sig = bool(shalf.get("opposite_significant_halves", False))
    if opp_sig:
        reasons.append("split-half produced opposite significant effects — non-stationary drift suspected")

    checks_list = [ok_d, ok_p, ok_stab, ok_wf, ok_white]
    n_ok = sum(checks_list)
    grade = "A" if n_ok == 5 and not reasons else ("B" if n_ok >= 4 else ("C" if n_ok == 3 else "D"))

    # Hard statistical caps:
    # 1) If scan-corrected null test fails, cap at D.
    if not ok_p:
        grade = "D"

    # 2) Strong monotonic trend cap (Spearman |rho| >= 0.85):
    #    level_shift on a smooth monotone axis -> cap at C (a mean split on a trend is not evidence)
    #    other detectors (slope_break, detrended_jump, etc.) -> cap at B (they measure shape changes)
    if is_strong_monotone:
        reasons.append(
            f"strong monotonic trend Spearman rho={rho:.2f} (detector={detector}) — break threshold may reflect smooth trend rather than discrete shift"
        )
        if detector == "level_shift":
            if grade in ("A", "B"):
                grade = "C"
        else:
            if grade == "A":
                grade = "B"

    # 3) Hard cap at C if multi-window stability or walk-forward fails (never call unstable/unvalidated break Grade B)
    if (not ok_stab or not ok_wf) and grade in ("A", "B"):
        grade = "C"

    # 4) Non-specific null or AR/random-walk failure or collapsing permutation control: cap at C
    if (not ok_white or not ok_perm_ctrl or not ok_shuffled or not ok_ar1 or opp_sig) and grade in ("A", "B"):
        grade = "C"

    # 5) Compound falsification failure -> Grade D (no evidence):
    #    - Failing the autocorrelated surrogate alongside instability, WF failure, white-noise failure, or split-half reversal
    #    - Multi-window instability combined with opposite significant split halves (non-stationary wandering drift)
    compound_ar = (not ok_ar1) and (not ok_stab or not ok_wf or not ok_white or opp_sig)
    compound_drift = (not ok_stab) and opp_sig
    if (compound_ar or compound_drift) and grade != "D":
        reasons.append(
            "compound falsification failure (autocorrelated/wandering non-stationary drift) — downgraded to Grade D"
        )
        grade = "D"

    if detector == "deseasonalized_shift" and is_strong_monotone and grade == "B":
        reasons.append(
            "boundary case: FFT deseasonalization followed by a mean shift on a strongly monotonic series "
            "is the border between a regime change and a trend with its seasonal cycle removed; "
            "Grade B names that border and is not a stronger claim"
        )

    verdict = {
        "A": "strong evidence (under this protocol — independent replication required)",
        "B": "moderate evidence",
        "C": "weak evidence — do not base decisions on this threshold",
        "D": "no evidence — do not announce a threshold",
    }[grade]

    return {
        "grade": grade,
        "verdict": verdict,
        "reasons": reasons,
        "checks": {
            "cohen_d_ok": ok_d,
            "p_perm_ok": ok_p,
            "stability_ok": ok_stab,
            "walkforward_ok": ok_wf,
            "white_null_ok": ok_white,
            "perm_control_ok": ok_perm_ctrl,
            "shuffled_null_ok": ok_shuffled,
            "ar1_surrogate_ok": ok_ar1,
            "split_half_consistent": not opp_sig,
        },
        "n_checks_passed": int(n_ok),
    }

